/** Pack Blender-baked movement curves; no mesh or attack data is replaced. */
import fs from "node:fs";
import path from "node:path";
import * as THREE from "three";
import { GLTFLoader } from "three/examples/jsm/loaders/GLTFLoader.js";
const directory = process.argv[2];
if (!directory) throw Error("Pass the movement export directory.");
const manifest = JSON.parse(
  fs.readFileSync(path.join(directory, "manifest.json"), "utf8"),
);
const data = { schema: 1, clips: {} };
for (const [name, metadata] of Object.entries(manifest.clips)) {
  const bytes = fs.readFileSync(
    path.resolve(directory, metadata.file ?? name + ".glb"),
  );
  const gltf = await new GLTFLoader().parseAsync(
    bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength),
    "",
  );
  const clip = gltf.animations[0];
  if (!clip || Math.abs(clip.duration - metadata.duration) > 1e-5)
    throw Error("Bad clip " + name);
  clip.optimize();
  const tracks = clip.tracks.filter(
    (t) =>
      /^Hips\.(position|quaternion)$/.test(t.name) ||
      /^(Left|Right)(UpLeg|Leg|Foot|ToeBase)\.(position|quaternion)$/.test(
        t.name,
      ),
  );
  if (tracks.length !== 18)
    throw Error("Missing locomotion tracks " + name + ": " + tracks.length);
  const carryTracks = clip.tracks.filter(
    (t) =>
      /^(Left|Right)(Arm|ForeArm|Hand)\.quaternion$/.test(t.name) ||
      /^weapon_hammer\.(position|quaternion)$/.test(t.name),
  );
  if (carryTracks.length !== 8)
    throw Error("Missing carry tracks " + name + ": " + carryTracks.length);
  // Fixed-length local offsets pick up sub-micron bake noise. Collapse those
  // translation curves within 0.001 rig units (0.01 mm on this centimetre rig).
  for (let i = 0; i < tracks.length; i++) {
    const t = tracks[i];
    if (
      /^(Left|Right)(UpLeg|Leg|Foot|ToeBase)\.position$/.test(t.name) &&
      t.values.every((v, j) => Math.abs(v - t.values[j % 3]) < 0.001)
    )
      tracks[i] = new THREE.VectorKeyframeTrack(
        t.name,
        [0],
        Array.from(t.values.slice(0, 3)),
      );
  }
  tracks.push(...carryTracks);
  const mixer = new THREE.AnimationMixer(gltf.scene);
  const action = mixer.clipAction(clip);
  action.setLoop(THREE.LoopOnce, 1);
  action.clampWhenFinished = true;
  action.play();
  const footTracks = ["Left", "Right"].flatMap((side) => [
    { name: side + "FootTarget.position", times: [], values: [] },
    { name: side + "FootTarget.quaternion", times: [], values: [] },
    { name: side + "KneeTarget.position", times: [], values: [] },
  ]);
  for (let i = 0; i < metadata.frames; i++) {
    const time = (i / (metadata.frames - 1)) * metadata.duration;
    mixer.setTime(time);
    gltf.scene.updateMatrixWorld(true);
    for (const track of footTracks) {
      const boneName = track.name.split("Target")[0].replace("Knee", "Leg");
      const foot = gltf.scene.getObjectByName(boneName);
      track.times.push(time);
      track.values.push(
        ...(track.name.endsWith(".quaternion")
          ? foot.getWorldQuaternion(new THREE.Quaternion()).toArray()
          : foot.getWorldPosition(new THREE.Vector3()).toArray()),
      );
    }
  }
  for (const track of footTracks) {
    const curve = track.name.endsWith(".quaternion")
      ? new THREE.QuaternionKeyframeTrack(track.name, track.times, track.values)
      : new THREE.VectorKeyframeTrack(track.name, track.times, track.values);
    tracks.push(curve.optimize());
  }
  const weights =
    metadata.slide_weights ??
    Array(metadata.frames).fill(name === "slide" ? 1 : 0);
  if (weights.length !== metadata.frames)
    throw Error("Bad slide weights " + name);
  tracks.push(
    new THREE.NumberKeyframeTrack(
      "Slide.weight",
      weights.map((_, i) => (i / (metadata.frames - 1)) * metadata.duration),
      weights,
    ).optimize(),
  );
  mixer.stopAllAction();
  mixer.uncacheRoot(gltf.scene);
  data.clips[name] = {
    duration: metadata.duration,
    loop: metadata.loop,
    tracks: tracks.map((t) => ({
      name: t.name,
      times: Array.from(t.times).map((n) => +n.toFixed(7)),
      values: Array.from(t.values).map((n) => +n.toFixed(7)),
    })),
  };
}
const target = "src/components/iron-vanguard/ironVanguardMovement.generated.ts";
const preamble =
  "// Generated by scripts/iron-vanguard/pack_movement.mjs from Blender movement exports.\n// Source: " +
  directory.replaceAll("\\", "/") +
  "; see manifest.json and movement.blend.\nexport interface MovementClipData { duration: number; loop: boolean; tracks: {name: string; times: number[]; values: number[]}[] }\nexport const IRON_VANGUARD_MOVEMENT: {schema: number; clips: Record<string, MovementClipData>} = ";
fs.writeFileSync(target, preamble + JSON.stringify(data) + ";\n");
console.log(
  JSON.stringify({
    target,
    bytes: fs.statSync(target).size,
    clips: Object.keys(data.clips),
  }),
);

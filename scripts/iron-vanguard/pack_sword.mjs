import fs from "node:fs";
import * as THREE from "three";
const directory = process.argv[2];
if (!directory) throw Error("Pass the sword export directory");
const source = JSON.parse(
  fs.readFileSync(directory + "/sword-source.json", "utf8"),
);
const tracks = [];
for (const [name, values] of Object.entries(source.tracks)) {
  if (/Toe/.test(name)) continue;
  const q = values.map((v) => new THREE.Quaternion().fromArray(v).normalize());
  for (let i = 1; i < q.length; i++)
    if (q[i - 1].dot(q[i]) < 0) q[i].set(-q[i].x, -q[i].y, -q[i].z, -q[i].w);
  const t = new THREE.QuaternionKeyframeTrack(
    name + ".quaternion",
    source.times,
    q.flatMap((v) => v.toArray()),
  ).optimize();
  tracks.push({
    name,
    times: Array.from(t.times),
    values: Array.from(t.values).map((n) => +n.toFixed(8)),
  });
}
const data = {
  duration: source.duration,
  sourceAction: source.action,
  sourceSignature: source.signature,
  gripMatrix: source.gripMatrix,
  tracks,
};
fs.writeFileSync(
  "src/components/iron-vanguard/ironVanguardSword.generated.ts",
  "// Generated by scripts/iron-vanguard/pack_sword.mjs from approved IV_Sword_Idle.\nexport const VANGUARD_SWORD_IDLE = " +
    JSON.stringify(data) +
    ";\n",
);
console.log(
  JSON.stringify({ tracks: tracks.length, bytes: JSON.stringify(data).length }),
);
